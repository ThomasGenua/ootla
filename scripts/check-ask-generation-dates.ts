import assert from 'node:assert/strict';
import {formatAssistantDate,formatAssistantTime,formatAssistantDateTime,formatAssistantTextDates,isAssistantTimeZone} from '../shared/assistant-dates.js';
import {askMessageSchema} from '../shared/conversation-contracts.js';
import {aiRequestSchema} from '../shared/ai-contracts.js';
const now=new Date('2026-10-29T01:30:00Z'),zone='America/New_York';
assert.equal(formatAssistantDateTime('2026-10-29T03:00:00Z',zone,now),'Today at 11 PM');
assert.equal(formatAssistantDateTime('2026-10-29T15:30:00Z',zone,now),'Tomorrow at 11:30 AM');
assert.equal(formatAssistantDateTime('2026-10-29T15:30:00Z','UTC',now),'Today at 3:30 PM');
assert.equal(formatAssistantDate('2026-10-29',zone,now),'Tomorrow');
assert.equal(formatAssistantDate('2026-10-28',zone,now),'Today');
assert.equal(formatAssistantDate('2026-11-02',zone,now),'Nov 2');
assert.equal(formatAssistantTime('2026-03-08T06:59:00Z',zone),'1:59 AM');
assert.equal(formatAssistantTime('2026-03-08T07:00:00Z',zone),'3 AM');
assert.equal(formatAssistantTime('2026-11-01T05:30:00Z',zone),'1:30 AM');
assert.equal(formatAssistantTime('2026-11-01T06:30:00Z',zone),'1:30 AM');
const text=formatAssistantTextDates('Due 2026-10-29T15:30:00Z. Calendar /admin/calendar?date=2026-10-30. Link https://example.test/2026-10-29. Invalid 2026-02-31.',zone,now);
assert(text.includes('Due Tomorrow at 11:30 AM.'));assert(text.includes('/admin/calendar?date=2026-10-30'));assert(text.includes('https://example.test/2026-10-29'));assert(text.includes('Invalid 2026-02-31.'));
assert(!isAssistantTimeZone('Mars/Ootla'));assert(isAssistantTimeZone(zone));assert(isAssistantTimeZone('UTC'));
const requestKey='d5ef951e-e9d9-4a5a-8a54-124618ae77a1',propertyId='e3d6c856-c80f-4480-b0df-1bdb007e4dd4';
assert(askMessageSchema.safeParse({requestKey,message:'What needs attention?',timeZone:zone}).success);
assert(!askMessageSchema.safeParse({requestKey,message:'What needs attention?',timeZone:'Mars/Ootla'}).success);
assert(aiRequestSchema.safeParse({requestKey,message:'Read availability',propertyId,timeZone:zone}).success);
assert(!aiRequestSchema.safeParse({requestKey,message:'Read availability',propertyId,timeZone:'Mars/Ootla'}).success);
console.log('PASS viewer-local Today/Tomorrow, date-only stability, spring/fall DST, humanized valid timestamps, unchanged URLs/invalid values, and request timezone validation.');
